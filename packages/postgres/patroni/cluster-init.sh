#!/bin/sh

set -eu

pgdata=/var/lib/postgresql/pgdata
restore_directory=/var/lib/postgresql/restore

# NOTE: the chart sets BACKUP_BUCKET only when backup.enabled is true
if [ -n "${BACKUP_BUCKET+set}" ] && [ ! -d "${restore_directory}" ]; then
  # NOTE: info prints its errors to stdout, and exits 0 with "status: error (other)" when it can't read the repo
  if ! stanza_info=$(pgbackrest --stanza="${STANZA}" info); then
    echo "${stanza_info}"
    echo "Failed to read stanza '${STANZA}'."
    exit 1
  fi
  case "${stanza_info}" in
    *"status: error (missing stanza path)"*)
      echo "Stanza '${STANZA}' does not exist. Creating..."
      if pgbackrest --stanza="${STANZA}" stanza-create; then
        echo "✓ Stanza '${STANZA}' created successfully."
      else
        echo "Failed to create stanza '${STANZA}'."
        exit 1
      fi
      ;;
    *"status: ok"* | *"status: error (no valid backups)"*)
      echo "Stanza '${STANZA}' already exists. Skipping stanza creation."
      ;;
    *)
      echo "${stanza_info}"
      echo "Failed to read stanza '${STANZA}'."
      exit 1
      ;;
  esac

  echo "Checking for existing backup..."
  if echo "${stanza_info}" | grep -q "full backup"; then
    echo "Full backup already exists. Restoring..."
    pg_ctl stop -w -D "${pgdata}" -m fast

    # NOTE: keep Patroni's config on the PVC outside pgdata so restarts mid-restore still resume
    mkdir -p "${restore_directory}.tmp"
    cp "${pgdata}/postgresql.conf" "${pgdata}/pg_hba.conf" "${pgdata}/postgresql.auto.conf" "${restore_directory}.tmp/"
    mv "${restore_directory}.tmp" "${restore_directory}"
    # NOTE: drop the marker on shell failure so Patroni's retry starts fresh; signal kills keep it for entrypoint.sh
    trap 'rm -rf "${restore_directory}"' EXIT
  fi
fi

if [ -d "${restore_directory}" ]; then
  if [ ! -f "${restore_directory}/restored" ]; then
    # NOTE: archive-get exits 1 only for a missing segment; Postgres ends recovery on any failure
    if pgbackrest --stanza="${STANZA}" restore \
      --recovery-option="restore_command=until pgbackrest --stanza=${STANZA} archive-get %f \"%p\"; do [ \$? -eq 1 ] && exit 1; sleep 10; done"; then
      echo "✓ Full backup restored successfully."
    else
      echo "Failed to restore full backup."
      exit 1
    fi

    {
      cat "${restore_directory}/postgresql.auto.conf"
      sed -n '/^# Recovery settings generated by pgBackRest/,$p' "${pgdata}/postgresql.auto.conf"
    } > "${pgdata}/postgresql.auto.conf.tmp"
    mv "${pgdata}/postgresql.auto.conf.tmp" "${pgdata}/postgresql.auto.conf"
    cp "${restore_directory}/postgresql.conf" "${restore_directory}/pg_hba.conf" "${pgdata}/"
    # NOTE: Patroni's cached cluster config, which a later Patroni start would load into the DCS
    rm -f "${pgdata}/patroni.dynamic.json"

    echo "Patching stanza..."
    if pgbackrest --stanza="${STANZA}" --no-online stanza-upgrade; then
      echo "✓ Stanza upgraded successfully."
    else
      echo "Failed to upgrade stanza."
      exit 1
    fi

    touch "${restore_directory}/restored"
  fi

  if [ -f "${pgdata}/recovery.signal" ]; then
    # NOTE: hot_standby=off accepts settings below the backup's; -W since pg_ctl's wait stops at 60s
    pg_ctl start -W -D "${pgdata}" -o "-c hot_standby=off"
    echo "Waiting for recovery to finish..."
    until pg_isready -q; do
      sleep 10
      pg_ctl status -D "${pgdata}" > /dev/null
    done
    pg_ctl stop -w -D "${pgdata}" -m fast
  fi

  # NOTE: drop the retrying restore_command and hot_standby=off override before Patroni takes over
  cp "${restore_directory}/postgresql.auto.conf" "${pgdata}/postgresql.auto.conf"
  pg_ctl start -w -D "${pgdata}"

  replicator_action=CREATE
  if psql -Atq -d postgres -c "SELECT 1 FROM pg_roles WHERE rolname='replicator'" | grep -q 1; then
    replicator_action=ALTER
  fi
  # NOTE: entrypoint.sh skips Patroni's post_bootstrap role step, so sync replicator before the backup
  printf "%s ROLE replicator WITH LOGIN REPLICATION PASSWORD :'password';\n" "${replicator_action}" \
    | psql -d postgres -v ON_ERROR_STOP=1 -v password="${REPLICATION_PASSWORD}"
fi

if psql -Atq -d postgres -c "SELECT 1 FROM pg_database WHERE datname='${POSTGRES_DB}'" | grep -q 1; then
  echo "Database '${POSTGRES_DB}' already exists. Skipping creation."
else
  echo "Database '${POSTGRES_DB}' does not exist. Creating..."
  if psql -d postgres -c "CREATE DATABASE ${POSTGRES_DB};"; then
    echo "✓ Database '${POSTGRES_DB}' created successfully."
  else
    echo "Failed to create database '${POSTGRES_DB}'."
    exit 1
  fi
fi

echo "Creating pg_stat_statements extension..."
if psql -d "${POSTGRES_DB}" -c "CREATE EXTENSION IF NOT EXISTS pg_stat_statements;"; then
  echo "✓ pg_stat_statements extension created successfully."
else
  echo "Warning: Failed to create pg_stat_statements extension."
fi

if psql -Atq -d postgres -c "SELECT 1 FROM pg_roles WHERE rolname='admin'" | grep -q 1; then
  echo "Role 'admin' already exists. Skipping creation."
else
  echo "Role 'admin' does not exist. Creating..."
  if psql -d "${POSTGRES_DB}" -c "
    CREATE ROLE admin WITH LOGIN PASSWORD '${ADMIN_PASSWORD}';
    GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO admin;
    GRANT CREATE ON SCHEMA public TO admin;
  "; then
    echo "✓ Role 'admin' created successfully."
  else
    echo "Failed to create role 'admin'."
    exit 1
  fi
fi

if psql -Atq -d postgres -c "SELECT 1 FROM pg_roles WHERE rolname='client'" | grep -q 1; then
  echo "Role 'client' already exists. Skipping creation."
else
  echo "Role 'client' does not exist. Creating..."
  if psql -d "${POSTGRES_DB}" -c "
    CREATE ROLE client WITH LOGIN PASSWORD '${CLIENT_PASSWORD}';
    GRANT CONNECT, TEMPORARY ON DATABASE ${POSTGRES_DB} TO client;
    GRANT USAGE ON SCHEMA public TO client;
    ALTER DEFAULT PRIVILEGES FOR ROLE admin IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO client;
    ALTER DEFAULT PRIVILEGES FOR ROLE admin IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO client;
    ALTER DEFAULT PRIVILEGES FOR ROLE admin IN SCHEMA public GRANT EXECUTE ON FUNCTIONS TO client;
  "; then
    echo "✓ Role 'client' created successfully."
  else
    echo "Failed to create role 'client'."
    exit 1
  fi
fi

if [ -z "${BACKUP_BUCKET+set}" ]; then
  echo "Backups are disabled. Skipping the initial full backup."
elif [ -d "${restore_directory}" ]; then
  # NOTE: replicas clone the newest backup, so they'd bring back the pre-restore one's settings
  until pgbackrest --stanza="${STANZA}" backup --type=full; do
    echo "Failed to create the restored cluster's full backup. Retrying in 10s..."
    sleep 10
  done
  rm -rf "${restore_directory}"
  echo "✓ Full backup created successfully. Replicas can now bootstrap."
elif pgbackrest --stanza="${STANZA}" backup --type=full; then
  echo "✓ Initial full backup created successfully. Replicas can now bootstrap."
else
  echo "Warning: Failed to create initial backup. Replicas may fail to bootstrap."
fi
